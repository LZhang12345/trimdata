def load_bank(cfg, checked, build_jsonl):
    """Root banks.load() with the BENCH6 counts table (Root's START COUNTS lists only POPE/VQAv2/VizWiz)."""
    value = protocol(cfg["bench6_protocol"])
    scope = checked(cfg["frozen_scope"])["banks"][cfg["bank"]]
    require(isinstance(scope.get("components"), list) and len(scope["components"]) == 1,
            "One exact frozen native component required")
    component = scope["components"][0]
    require(scope["qa_access"] == "authorized" and scope["metric"] == cfg["bank"] == value["bank"]
            and scope["edition"] == value["edition"] and scope["split"] == value["split"]
            and component["name"] == value["component"], "No image-only permission expansion; exact bank scope")
    require(cfg["media"] == scope["media"] == value["media"] and cfg["native_source"] == component["source"]
            == value["native_source"] and component["support"] == value["support"]
            and component["provider_complete"] == value["provider_complete"],
            "Exact configured frozen source/support/provider/media descriptors required")
    roster = build_jsonl(cfg["bank"], scope, component["source"], component["support"])
    media = checked(scope["media"])
    provider = checked(component["provider_complete"])
    require(provider["status"] == PROVIDER_STATUS and provider["frozen_support"] == component["support"]
            and provider["media"] == scope["media"] and provider.get("metric", cfg["bank"]) == cfg["bank"],
            "Genuine actual input provider differs")
    require(provider.get("QA_count", value["questions"]) == value["questions"]
            and provider.get("image_count", value["images"]) == value["images"], "Provider counts differ")
    require((len(roster["records"]), len(media["images"])) == COUNTS[cfg["bank"]]
            and {r["image_reference"] for r in roster["records"]} == set(media["images"]),
            "Full native bank/media membership differs")
    return roster, media


def bound_inputs(cfg, c, fingerprint, build_jsonl):
    """Root worker.bound_inputs() over load_bank(): exact original archive snapshot and complete RGB proofs."""
    roster, inventory = load_bank(cfg, c.checked, build_jsonl)
    support = c.checked(roster["support"])
    archive = support["media_source"]
    require(archive == cfg["archive_mapping"]["archive"] and c.desc(archive["path"]) == archive,
            "Actual qualified original image archive changed")
    snapshot = fingerprint(archive["path"])
    proof_refs = {c.key(v["source_proof"]): v["source_proof"] for v in inventory["images"].values()}
    proofs = {k: c.checked(v) for k, v in proof_refs.items()}
    for value in inventory["images"].values():
        proof = proofs[c.key(value["source_proof"])]["images"][value["source_proof_key"]]
        require(all(proof.get(k) == value[k] for k in ("encoded_bytes", "encoded_sha256", "rgb_sha256", "width",
                                                        "height")), "Real complete RGB proof/media identity differs")
    return roster, inventory, snapshot


def _hex64(value):
    return isinstance(value, str) and re.fullmatch(r"[0-9a-f]{64}", value) is not None


def _image_path(value, family):
    require(type(value) is str and 0 < len(value) <= 512 and "\0" not in value and "\\" not in value,
            "Image must be a bounded literal relative path")
    path = PurePosixPath(value)
    require(not path.is_absolute() and str(path) == value and all(p not in ("", ".", "..") for p in path.parts),
            "Image path must be canonical and relative")
    if family == "seed":
        require(len(path.parts) == 2 and path.parts[0] == "SEED-Bench-image", "SEED image subset path required")
    return value


def validate_roster(name, records):
    """Exact answer-free full roster with source-row identity; returns order-sensitive commitments."""
    value = protocol(name)
    require(isinstance(records, list) and len(records) == value["questions"],
            "Exact full official question count required: %d" % value["questions"])
    source = value["native_source"]["sha256"]
    keys, indices, images, natives = [], [], [], []
    for row in records:
        require(isinstance(row, dict), "Roster rows must be objects")
        native = row.get("native_input")
        require(isinstance(native, dict) and set(native) == {"question_id", "image", "text"},
                "Native input must be exactly question_id/image/text")
        require(not any(field in row or field in native for field in FORBIDDEN_FIELDS),
                "Answer or label fields must never enter the generation roster")
        require(row.get("bank") == value["bank"] and row.get("source_sha256") == source,
                "Roster bank/source identity differs")
        index = row.get("original_row_index")
        require(type(index) is int and index >= 0, "Original row index required")
        qid = native["question_id"]
        require(type(qid) is int or (type(qid) is str and 0 < len(qid) <= 512),
                "Native question ID must be an int or bounded nonempty string")
        require(type(row.get("native_id")) is type(qid) and row["native_id"] == qid, "Native ID/type differs")
        require(_hex64(row.get("semantic_key")), "Semantic QA key must be a lowercase SHA256")
        text = native["text"]
        require(isinstance(text, str) and text.strip() and len(text) <= 16384, "Bounded nonempty prompt required")
        image = _image_path(native["image"], value["family"])
        require(row.get("image_reference") == value["component"] + ":" + image, "Explicit image provider reference")
        keys.append(row["semantic_key"])
        indices.append(index)
        images.append(image)
        natives.append((type(qid).__name__, qid))
    require(len(set(keys)) == len(keys), "Duplicate semantic QA key")
    require(all(a < b for a, b in zip(indices, indices[1:])), "Rows must keep strictly increasing source order")
    require(len(set(images)) == value["images"], "Exact unique image count required: %d" % value["images"])
    summary = {
        "protocol": name, "bank": value["bank"], "split": value["split"], "questions": len(records),
        "unique_images": len(set(images)), "source_sha256": source,
        "ordered_semantic_keys_sha256": key(keys), "ordered_question_ids_sha256": key([list(x) for x in natives]),
        "ordered_native_inputs_sha256": key([r["native_input"] for r in records]),
        "duplicate_native_question_ids": sum(count - 1 for count in Counter(natives).values() if count > 1),
        "answer_or_label_fields_present": False,
    }
    if value["family"] == "mme":
        categories = Counter()
        require(all(type(r["native_input"]["question_id"]) is str
                    and r["native_input"]["question_id"] == r["native_input"]["image"] for r in records),
                "LLaVA MME question_id must be the image path the official converter parses")
        for first, second in zip(records[0::2], records[1::2]):
            require(first["native_input"]["image"] == second["native_input"]["image"],
                    "MME questions must come in consecutive same-image pairs (official acc+ chunking)")
            category = first["native_input"]["image"].split("/")[0]
            require(category in value["categories"], "MME category outside this bank")
            categories[category] += 2
        require(set(categories) == set(value["categories"]), "Every MME subtask of this bank required")
        summary["questions_per_category"] = dict(sorted(categories.items()))
    return summary


def questions(records):
    """Native question rows in roster order, exactly as the LLaVA loader reads them."""
    return [copy.deepcopy(row["native_input"]) for row in records]


def journal_function(name, cell, model, roster_summary, sources_sha256):
    """Resume-stable per-bank journal identity: no job, node, attempt or route fields."""
    value = protocol(name)
    require(isinstance(model, dict) and _hex64(model.get("parameter_sha256"))
            and _hex64(model.get("auxiliary_identity_sha256"))
            and isinstance(model.get("generation_config"), dict)
            and type(model.get("adapter_active")) is bool, "Exact loaded model identity required")
    require(isinstance(roster_summary, dict) and roster_summary.get("protocol") == name
            and roster_summary.get("questions") == value["questions"], "Roster summary must belong to this protocol")
    require(_hex64(sources_sha256), "Bound source closure digest required")
    return {
        "schema": "tool1-bench6-bank-function-v1", "role": ROLE, "protocol": name,
        "bank": value["bank"], "split": value["split"], "edition": value["edition"], "cell": cell,
        "model_identity_sha256": model["parameter_sha256"],
        "auxiliary_identity_sha256": model["auxiliary_identity_sha256"],
        "model_generation_config": copy.deepcopy(model["generation_config"]),
        "adapter_active": model["adapter_active"], "adapter_merged": False,
        "full_roster_sha256": roster_summary["ordered_semantic_keys_sha256"],
        "native_inputs_sha256": roster_summary["ordered_native_inputs_sha256"],
        "decoding": copy.deepcopy(value["decoding"]), "prompt_policy": value["prompt_policy"],
        "kernel": value["kernel"], "native_source": copy.deepcopy(value["native_source"]),
        "support": copy.deepcopy(value["support"]), "media": copy.deepcopy(value["media"]),
        "start_template": copy.deepcopy(START_TEMPLATE), "sources_sha256": sources_sha256,
        "llava_revision": LLAVA_REVISION,
    }


def completion(name, accepted, missing):
    value = protocol(name)
    require(type(accepted) is int and type(missing) is int and missing >= 0 and accepted >= 0,
            "Integer accepted/missing counts required")
    require(accepted + missing == value["questions"], "Accepted plus missing must equal the full bank")
    return {"protocol": name, "questions": value["questions"], "accepted": accepted, "missing": missing,
            "complete": missing == 0 and accepted == value["questions"]}


def parse_predictions(raw, records):
    """Exported per-QA LLaVA answer rows aligned one-to-one with the roster order (IDs may repeat)."""
    require(isinstance(raw, bytes) and raw.endswith(b"\n"), "Complete newline-terminated JSONL required")
    lines = raw[:-1].split(b"\n")
    require(len(lines) == len(records), "Prediction count differs from the full roster")
    result = []
    for row, line in zip(records, lines):
        value = json.loads(line)
        native = row["native_input"]
        require(isinstance(value, dict) and {"question_id", "prompt", "text"} <= set(value),
                "Native LLaVA answer row fields required")
        require(type(value["question_id"]) is type(native["question_id"])
                and value["question_id"] == native["question_id"], "Prediction order or ID type differs")
        require(value["prompt"] == native["text"], "Prediction prompt differs from the frozen question")
        require(isinstance(value["text"], str), "Generated text must be a string, including empty output")
        require(not any(field in value for field in FORBIDDEN_FIELDS), "Predictions must not carry label fields")
        result.append({"question_id": value["question_id"], "prompt": value["prompt"], "text": value["text"]})
    return result
